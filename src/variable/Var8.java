package variable;

public class Var8 {
    public static void main(String[] args) {
        //정수
        byte b= 127; //-128~127
        short s = 32767; // - 32768 ~ 32767
        int i = 2147483647; // -2147483648 ~ 2147483647
        long l = 9223372036854775807L; // 뒤에 꼭 L이나 l을 붙여줘야 한다

        //실수
        float f = 10.0f; // 뒤에 f를 붙여줘야 한다
        double d = 10.0;
    }
}
